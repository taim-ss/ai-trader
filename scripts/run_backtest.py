"""Run the pre-specified backtest on cached daily prices and write a report.

Pre-specified before running (no tuning on this data):
- universe: liquid US sector and broad ETFs (list below)
- strategy: 12-1 momentum, top 3, 15% cap per name (from config/risk_limits.yaml)
- costs: 10 bps slippage, 15 bps FX, 0 commission
Sensitivity (reported, not used to pick the result): cap 33% per name.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
import requests  # noqa: E402
import truststore  # noqa: E402

from ai_trader.backtest import CostModel, metrics, run_backtest  # noqa: E402
from ai_trader.data import load_prices  # noqa: E402
from ai_trader.risk import load_limits  # noqa: E402
from ai_trader.strategy import StrategyConfig  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
UNIVERSE = ["SPY", "QQQ", "IWM", "EFA", "EEM", "TLT", "GLD", "XLE", "XLK", "XLV", "XLF", "XLI", "XLP", "XLU"]
BENCHMARKS = ["SPY", "URTH"]
START = date(2013, 1, 2)
END = date(2026, 10, 23)


def buy_and_hold(prices: pd.Series, start_value: float = 1000.0) -> pd.Series:
    return start_value * prices / prices.iloc[0]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="require cached files; never fetch prices")
    args = parser.parse_args()
    symbols = sorted(set(UNIVERSE) | set(BENCHMARKS))
    if args.offline:
        missing = [s for s in symbols if not (ROOT / "data" / f"{s}_{START}_{END}.csv").exists()]
        if missing:
            print(f"missing cache files: {', '.join(missing)}", file=sys.stderr)
            return 1
    truststore.inject_into_ssl()
    session = requests.Session()
    prices = load_prices(session, symbols, START, END, ROOT / "data")
    if len(prices) < 300:
        print(f"only {len(prices)} rows after alignment; aborting", file=sys.stderr)
        return 1

    limits = load_limits(ROOT / "config" / "risk_limits.yaml")
    universe_prices = prices[UNIVERSE]
    costs = CostModel()
    primary_cfg = StrategyConfig(top_n=3, single_name_cap=limits.max_position_weight)
    sensitivity_cfg = StrategyConfig(top_n=3, single_name_cap=1 / 3)

    curves = {
        "strategy (cap 15%)": run_backtest(universe_prices, primary_cfg, costs),
        "strategy (cap 33%, sensitivity)": run_backtest(universe_prices, sensitivity_cfg, costs),
        "SPY buy and hold": buy_and_hold(prices["SPY"]),
        "URTH buy and hold": buy_and_hold(prices["URTH"]),
    }
    rows = []
    for name, curve in curves.items():
        m = metrics(curve)
        rows.append({"series": name, **{k: round(v, 4) for k, v in m.items()}})
    table = pd.DataFrame(rows).set_index("series")

    reports = ROOT / "reports"
    reports.mkdir(exist_ok=True)
    table.to_csv(reports / "backtest_metrics.csv")

    fig, ax = plt.subplots(figsize=(9, 5))
    for name, curve in curves.items():
        ax.plot(curve.index, curve.values, label=name)
    ax.set_title("Walk-forward monthly rebalance, costs included (strategy); buy and hold (benchmarks)")
    ax.set_ylabel("value of 1,000 (USD)")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(reports / "equity_curves.png", dpi=120)
    plt.close(fig)

    result_rows = []
    for name, curve in curves.items():
        m = metrics(curve)
        turnover = f"{m['annual_turnover']:.2f}x" if pd.notna(m["annual_turnover"]) else "not measured"
        result_rows.append(f"| {name} | {m['cagr']:.2%} | {m['max_drawdown']:.2%} | "
                           f"{m['sharpe']:.3f} | {m['sortino']:.3f} | {m['daily_hit_rate']:.2%} | {turnover} |")
    (reports / "REPORT.md").write_text(
        "# Corrected backtest report: monthly ETF momentum\n\n"
        "Status: historical research only; no broker fills or paper-trading performance. "
        "Not financial advice. Regenerated by `scripts/run_backtest.py`.\n\n"
        "This corrected simulation supersedes the earlier report: the earlier engine held weights "
        "constant each day, implying uncharged daily rebalancing, and filled at the signal close.\n\n"
        "## Setup\n\n"
        f"- Cached Yahoo adjusted-close data: {len(prices):,} aligned rows, "
        f"{prices.index[0].date()} to {prices.index[-1].date()}. No data redistribution.\n"
        f"- Universe: {', '.join(UNIVERSE)}. Same strategy and universe as the earlier run; no tuning.\n"
        "- Signal: 252-session lookback, latest 21 sessions skipped; top 3 positive scores. "
        "Primary cap 15% per name; 33% sensitivity only. Remaining allocation is cash.\n"
        "- Month-end signal uses data available at that close; execution is at the next observed "
        "session close. Existing holdings receive that session's return before execution. "
        "This is a close-only approximation, not a next-open fill simulation.\n"
        "- Dollar holdings drift between trades; rebalances include the cost of restoring target weights. "
        "Costs are 10 bps slippage + 15 bps FX per actual traded dollar value; commission 0, all assumptions. "
        "Post-cost equity and traded value are solved together. Cash earns 0%.\n\n"
        "## Results\n\n"
        "| Series | CAGR | Max drawdown | Sharpe | Sortino | Daily hit rate | Annual turnover |\n"
        "|---|---|---|---|---|---|---|\n" + "\n".join(result_rows) + "\n\n"
        "Daily hit rate is the fraction of all daily account returns above zero, including cash days; "
        "it is not a trade win rate. Annual turnover is gross buys plus sells divided by "
        "pre-trade equity, summed and divided by calendar years (two-sided turnover). "
        "Sharpe/Sortino use 252 annualisation and a zero risk-free rate.\n\n"
        "## Limits and interpretation\n\n"
        "- One historical path and a current surviving ETF universe; not a clean out-of-sample test. "
        "The rule design followed literature review. This correction is not a new holdout test.\n"
        "- The first 252 sessions are strategy warm-up in cash while the buy-and-hold benchmarks "
        "are invested from the start. This comparison includes that opportunity cost.\n"
        "- All account returns are USD. A flat FX fee does not model EUR/USD returns. "
        "EUR cash interest, spreads, taxes, and observed broker fills remain unmodelled.\n"
        "- Adjusted closes approximate reinvested distributions and splits; they are not executable quotes. "
        "Same-day execution bias is reduced by delaying fills, but close fills remain assumed.\n"
        "- SPY and URTH are ETF benchmark proxies, not direct index returns; benchmarks exclude "
        "transaction costs, whereas the strategy includes the stated assumptions.\n"
        "- The backtest does not simulate the paper engine's order caps, daily-loss/cooldown stops "
        "or drawdown kill switch. It is strategy research, not a broker execution replay.\n"
        "- Yahoo's public chart endpoint is unofficial; cached history lacks a point-in-time revision archive.\n\n"
        "Artifacts: `backtest_metrics.csv` and `equity_curves.png`. No live connection or orders "
        "are authorised by this report. Paper record and CHECKPOINT 4 remain outstanding.\n",
        encoding="utf-8",
    )

    print(table.to_string())
    print(f"\nrows: {len(prices)}  period: {prices.index[0].date()} to {prices.index[-1].date()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
